--Las funciones MAX y MIN sirven para traer el resultado mas reciente o el valor mas grande en caso de MAX y traer el resultado mas antiguo
-- o valor mas pequeño en caso de MIN.

--por ejemplo:

SELECT MAX (fechaPago) FROM pago

-- El resultado sera que trae la fecha mas reciente de pago


SELECT MIN (monto) From pago

-- El resultado sera que trae el monto mas pequeño de la tabla pago.

